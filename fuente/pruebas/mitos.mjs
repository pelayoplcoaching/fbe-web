// Mitos: progreso de leidos, Siguiente, copiar enlace, Uno al azar, filtro + indice, empezar de cero y apertura por #
import { chromium, servir, RAIZ } from './comun.mjs';
const srv = await servir(RAIZ, 8931);
const b = await chromium.launch(); let fallos = 0;
const ok = (c, m) => { console.log((c ? '  ✔ ' : '  ✘ ') + m); if (!c) fallos++; };
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8931/mitos.html');
const r = async () => p.evaluate(() => ({ l: document.getElementById('mitos-l').textContent, abiertos: [...document.querySelectorAll('.mito details[open]')].map(d => d.parentElement.id), leidos: document.querySelectorAll('.mito.leido').length }));
ok((await r()).l === '0', 'al empezar, 0 leídos');
await p.click('#estirar summary'); await p.waitForTimeout(200); let x = await r();
ok(x.l === '1' && x.abiertos.includes('estirar'), 'abrir un mito cuenta como leído');
await p.click('#estirar .mito-sig'); await p.waitForTimeout(600); x = await r();
ok(x.l === '2' && x.abiertos.includes('proteina-rinon'), '«Siguiente» abre el siguiente');
await p.click('#estirar .mito-copia'); await p.waitForTimeout(150);
ok((await p.evaluate(() => navigator.clipboard.readText())).endsWith('mitos.html#estirar'), 'copiar enlace del mito');
await p.click('#mitos-azar'); await p.waitForTimeout(600); x = await r();
ok(x.l === '3', '«Uno al azar» abre otro sin leer');
await p.reload(); await p.waitForTimeout(250);
ok((await r()).l === '3', 'el progreso se guarda al recargar');
await p.click('#mitos-f button[data-t="mayores"]'); await p.waitForTimeout(100);
await p.click('.mitos-indice a[href="#creatina"]'); await p.waitForTimeout(600);
const c = await p.evaluate(() => ({ oculto: document.getElementById('creatina').hidden, abierto: document.querySelector('#creatina details').open }));
ok(!c.oculto && c.abierto, 'el índice muestra y abre un mito oculto por el filtro');
await p.click('#mitos-reset'); await p.waitForTimeout(150);
ok((await r()).l === '0', '«Empezar de cero»');
await p.goto('http://localhost:8931/mitos.html#artrosis'); await p.waitForTimeout(400);
ok(await p.evaluate(() => document.querySelector('#artrosis details').open), 'se abre al llegar por #');
ok(errs.length === 0, 'sin errores ' + errs.join(' | '));
console.log(fallos ? 'FALLOS ' + fallos : 'todo correcto'); await b.close(); srv.close(); process.exit(0);
